@app.route("/bookings")
@login_required
def bookings():

    connection = get_db_connection()

    try:

        cursor = connection.cursor()


        # -------------------------------------------------
        # ALL BOOKINGS
        # -------------------------------------------------

        cursor.execute(
            """
            SELECT *
            FROM bookings
            ORDER BY id DESC
            """
        )

        bookings = cursor.fetchall()


        # -------------------------------------------------
        # TOTAL
        # -------------------------------------------------

        total_bookings = len(bookings)


        # -------------------------------------------------
        # PENDING
        # -------------------------------------------------

        cursor.execute(
            """
            SELECT COUNT(*)
            FROM bookings
            WHERE status = %s
            """,
            ("Pending",)
        )

        pending_bookings = cursor.fetchone()["count"]


        # -------------------------------------------------
        # IN PROGRESS
        # -------------------------------------------------

        cursor.execute(
            """
            SELECT COUNT(*)
            FROM bookings
            WHERE status = %s
            """,
            ("In Progress",)
        )

        in_progress_bookings = cursor.fetchone()["count"]


        # -------------------------------------------------
        # COMPLETED
        # -------------------------------------------------

        cursor.execute(
            """
            SELECT COUNT(*)
            FROM bookings
            WHERE status = %s
            """,
            ("Completed",)
        )

        completed_bookings = cursor.fetchone()["count"]


        # -------------------------------------------------
        # CANCELLED
        # -------------------------------------------------

        cursor.execute(
            """
            SELECT COUNT(*)
            FROM bookings
            WHERE status = %s
            """,
            ("Cancelled",)
        )

        cancelled_bookings = cursor.fetchone()["count"]

    finally:

        connection.close()


    # -----------------------------------------------------
    # RESPONSE
    # -----------------------------------------------------

    response = make_response(
        render_template(
            "bookings.html",
            bookings=bookings,
            total_bookings=total_bookings,
            pending_bookings=pending_bookings,
            in_progress_bookings=in_progress_bookings,
            completed_bookings=completed_bookings,
            cancelled_bookings=cancelled_bookings
        )
    )


    # Prevent old booking page cache

    response.headers[
        "Cache-Control"
    ] = (
        "no-store, no-cache, "
        "must-revalidate, max-age=0"
    )

    response.headers[
        "Pragma"
    ] = "no-cache"

    response.headers[
        "Expires"
    ] = "0"


    return response


